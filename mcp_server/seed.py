def seed_database(connection: sqlite3.Connection) -> None:
    """Заполнить пустую базу каталогом, чтобы бот работал сразу после запуска."""
    connection.executemany(
        """
        INSERT OR IGNORE INTO courses (
            id, slug, title, language, level, format, weeks, lessons_per_week,
            price, old_price, description, audience, teacher
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """,
        COURSES,
    )
    connection.executemany(
        """
        INSERT OR IGNORE INTO modules (course_id, position, title, summary)
        VALUES (?, ?, ?, ?)
        """,
        MODULES,
    )
    connection.executemany(
        """
        INSERT OR IGNORE INTO groups (course_id, schedule, seats, format)
        VALUES (?, ?, ?, ?)
        """,
        GROUPS,
    )
    connection.executemany(
        """
        INSERT OR IGNORE INTO promos (code, discount_percent, description)
        VALUES (?, ?, ?)
        """,
        PROMOS,
    )
    connection.executemany(
        """
        INSERT OR IGNORE INTO faq (topic, question, answer)
        VALUES (?, ?, ?)
        """,
        FAQ,
    )


def sync_promo_conditions(connection: sqlite3.Connection) -> None:
    """Обновить условия промоакций в уже существующей базе.

    ``INSERT OR IGNORE`` не меняет описание существующего промокода, а именно в
    описании живёт правило «скидка только на один курс». Без этого шага старые
    базы продолжали бы отвечать формулировкой «на первый курс», и модель
    складывала скидку ко всем курсам заказа.

    Курсовые цены и заявки здесь не трогаются: их правит только пользователь.
    """
    connection.executemany(
        "UPDATE promos SET discount_percent = ?, description = ? WHERE code = ?",
        [(percent, description, code) for code, percent, description in PROMOS],
    )
